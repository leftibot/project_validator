"""Expected failures for the shell-reading bugs the corpus audit found (upstream #190 to #196 and #284): conditional
expressions and arrays, heredoc bodies, unreadable followed scripts, `exec`, custom `shell:` wrappers, commands dropped
without an Unknown, workflow `env:` and conditional `$GITHUB_ENV` exports.

Each test asserts the behaviour the upstream issue asks for; it fails until the bug is fixed, when its decorator goes.
"""

from __future__ import annotations

import json
import unittest
from collections.abc import Mapping

from project_validator.checks.ci_build_types import ci_build_types
from project_validator.checks.coverage import coverage
from project_validator.checks.hardening import hardening
from project_validator.checks.tests_run import tests_run
from project_validator.checks.warnings_as_errors import warnings_as_errors
from project_validator.core import Status
from project_validator.facts import Command, Facts, Unknown, resolved
from tests.support import GITHUB_WORKFLOW, github_job, github_steps, make_context, run_in_layout, temp_project

CI = "ubuntu-latest"
BATS = {"tests/shop.bats": '@test "sums the prices" {\n  run total 1 2\n}\n'}
CMAKE_DEBUG = "cmake -B build -DCMAKE_BUILD_TYPE=Debug"
KCOV_BATS = "kcov --exclude-path=/tmp coverage bats tests"
# A coursier launcher (scalameta's bin/scalafmt): a shell header, then the bytes of a zip.
LAUNCHER = '#!/usr/bin/env sh\nexec java -jar "$0" "$@"\n' + "PK\x03\x04\x00\x05\x06\x07it's \"x\x00\\" * 3
# The head of an autoconf-generated configure, and the quoting its case patterns use.
CONFIGURE = (
    "#! /bin/sh\n# Guess values for system-dependent variables and create Makefiles.\n"
    "# Generated by GNU Autoconf 2.71.\n" + "case $1 in #(\n  *\\'*) ac_val=\"\\\\\"*?[ ''\t' ;;\nesac\n" * 3
)


def _facts_of(files: Mapping[str, str]) -> Facts:
    """The facts of a throw-away project of `files`."""
    with temp_project(files) as root:
        context = make_context(root)
        return context.facts


def _argvs(facts: Facts) -> list[tuple[str, ...]]:
    """What the facts say runs, as argv tuples."""
    return [fact.argv for fact in facts.of(Command)]


def _workflow(job: Mapping[str, object], **top: object) -> dict[str, str]:
    """A workflow with the one job `job` (on `CI` unless it says where it runs) and `top` at the workflow level."""
    return {GITHUB_WORKFLOW: json.dumps({**top, "jobs": {"build": {"runs-on": CI, **job}}})}


def _script_run(path: str, text: str, *lines: str) -> dict[str, str]:
    """A repository script at `path` with `text`, and a CI job that runs `lines` (by default, the script itself)."""
    return {path: text, **github_job(CI, *(lines or (path,)))}


class ConditionalExpressionTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #190: `[[ ]]` continuation lines and `name=(…)` are read as commands
    def test_multi_line_conditionals_and_array_assignments_are_not_commands(self) -> None:
        """A `[[ … ]]` test that continues on the next line is one compound command, and `name=(…)` is an assignment:
        neither runs a program, so neither is an unknown variable program (Homebrew, Humanizer, scikit-learn)."""
        cases = {
            "two lines": 'if [[ "$A" != x ||\n  "$B" != y ]]; then echo; fi',
            "three lines": 'if [[ "$GITHUB_EVENT_NAME" == schedule ||\n  "$GITHUB_EVENT_NAME" == workflow_dispatch ||\n'
            '  "$COMMIT_MSG" =~ pyodide ]]; then echo; fi',
            "parenthesised": 'if [[ "$E" == "push" &&\n  ("$R" == "refs/heads/main") ]]; then echo; fi',
            "array": 'repos=("${GITHUB_REPOSITORY}")',
        }
        for name, script in cases.items():
            with self.subTest(case=name):
                facts = _facts_of(github_job(CI, script))
                self.assertFalse(facts.of(Unknown), facts.of(Unknown))
                self.assertFalse([argv for argv in _argvs(facts) if argv[0].startswith(("$", "[["))], _argvs(facts))


class HeredocTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #191: heredoc bodies are tokenised as shell commands
    def test_heredoc_bodies_are_data(self) -> None:
        """The body of `cat <<EOF … EOF` (redirected, inside `$(…)`, or in a followed script) is skipped: its prose and
        apostrophes are no commands, and the command after it is read (llama.cpp, cmake_template, package-lint,
        hledger)."""
        cases = {
            "redirected": github_job(CI, "cat > f << 'EOF'\nSome prose with it's apostrophe.\nEOF\ncmake -B build"),
            "in a substitution": github_job(CI, "X=$(cat <<'EOF'\nit's \"unbalanced\nEOF\n)\ncmake -B build"),
            "cat - in a substitution": github_job(CI, "x=$(cat - <<EOF\n(foo bar)\nEOF\n)\ncmake -B build"),
            "followed script": _script_run(
                "tools/lint", "#!/usr/bin/env bash\ncat <<EOF\nit's fine\nEOF\ncmake -B build\n"
            ),
        }
        for name, files in cases.items():
            with self.subTest(case=name):
                facts = _facts_of(files)
                self.assertFalse(facts.of(Unknown), facts.of(Unknown))
                self.assertIn(("cmake", "-B", "build"), _argvs(facts))
                self.assertFalse({("foo", "bar"), ("EOF",), ("Some", "prose")} & set(_argvs(facts)), _argvs(facts))


class FollowedScriptTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #192: a binary launcher or autoconf configure is tokenised as shell
    def test_an_unreadable_followed_script_is_at_most_one_unknown_naming_the_file(self) -> None:
        """A followed script that is not readable shell (a zip after a shebang, as scalafmt's and metals' launcher; a
        generated configure, as opam's) gives one Unknown naming the file, or none, never its bytes as commands."""
        for path, text, line in (
            ("bin/scalafmt", LAUNCHER, "./bin/scalafmt --test"),
            ("configure", CONFIGURE, "./configure"),
        ):
            with self.subTest(script=path):
                facts = _facts_of(_script_run(path, text, line))
                self.assertIn(tuple(line.split()), _argvs(facts))
                unknowns = [unknown for unknown in facts.of(Unknown) if unknown.origin.path == path]
                self.assertLessEqual(len(unknowns), 1, [unknown.subject for unknown in unknowns])
                self.assertTrue(all(path in unknown.subject for unknown in unknowns), unknowns)

    @unittest.expectedFailure  # upstream #193: `exec <program>` in a followed script is not a launcher
    def test_exec_runs_the_program_that_follows(self) -> None:
        """`exec bats tests` at the end of `test/run` runs bats, like `env` or `time` would (rbenv, bash-it): tests-run
        sees CI running the bats tests."""
        files = {**BATS, **_script_run("test/run", "#!/usr/bin/env bash\nexec bats ${CI:+--tap} tests\n")}
        self.assertIn(("bats", "${CI:+--tap}", "tests"), _argvs(_facts_of(files)))
        result = run_in_layout(self, "Shell scripts", tests_run, files)
        self.assertEqual(result.status, Status.PASS, result)


class CustomShellTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #194: `shell: msys2 {0}` / `script -c "bash {0}"` hide the step's script
    def test_a_shell_wrapper_that_runs_bash_has_its_script_split(self) -> None:
        """A custom `shell:` whose `{0}` is run by bash (msys2's shell, `script -q -e -c "bash {0}"`) runs the step's
        commands, so the cmake build type (fmt, simdjson) and the kcov coverage run (bats-core) are read."""
        msys2 = _workflow(
            {"runs-on": "windows-latest", "defaults": {"run": {"shell": "msys2 {0}"}}, "steps": [{"run": CMAKE_DEBUG}]}
        )
        wrapped = _workflow({"steps": [{"run": KCOV_BATS, "shell": 'script -q -e -c "bash {0}"'}]})
        with self.subTest(wrapper="msys2 {0}"):
            self.assertIn(tuple(CMAKE_DEBUG.split()), _argvs(_facts_of(msys2)))
            result = run_in_layout(self, "CMake C++", ci_build_types, msys2)
            self.assertFalse([detail for detail in result.details if "no build type specified" in detail], result)
        with self.subTest(wrapper='script -q -e -c "bash {0}"'):
            self.assertIn(tuple(KCOV_BATS.split()), _argvs(_facts_of(wrapped)))
            self.assertEqual(run_in_layout(self, "Shell scripts", coverage, wrapped).status, Status.PASS)


class UnknownCommandTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #195: commands the reader cannot resolve are dropped without an Unknown
    def test_unresolvable_commands_are_recorded_as_unknown(self) -> None:
        """A program with a variable prefix or directory, an expression program or step, a missing script, `docker run`,
        `earthly` and an unknown composite action each yield an Unknown, as `$CABAL v2-test` does (httpx, SwiftFormat,
        fpm, docker-library/postgres, ansible-for-devops, Awesome-CV, ecto, terraform-aws-modules)."""
        cases = {
            "variable prefix": _script_run("scripts/check", '#!/bin/sh -e\nexport PREFIX=""\n${PREFIX}ruff check .\n'),
            "variable directory": _script_run("lint.sh", '#!/bin/bash\n"$DIR/$TOOL" --lint .\n', "./lint.sh"),
            "expression program": github_steps('run: echo "TOOL=./x" >> $GITHUB_ENV', "run: ${{ env.TOOL }} test"),
            "expression step": github_steps("run: ${{ matrix.runs.test }}"),
            "missing script": github_steps("run: curl -o ci/test.sh https://example.com/x", "run: ci/test.sh"),
            "docker run": github_job(CI, 'docker run --rm -v "$PWD:/doc" img make test'),
            "earthly": {"Earthfile": "test:\n  RUN mix test\n", **github_job(CI, "earthly +test")},
            "unknown composite action": github_steps("uses: clowdhaus/terraform-composite-actions/pre-commit@v1.14.0"),
        }
        for name, files in cases.items():
            with self.subTest(case=name):
                facts = _facts_of(files)
                # The expression program may instead be resolved to the value the step before exported.
                followed = [resolved(command) for command in facts.of(Command) if command.argv[:1] != ("echo",)]
                self.assertTrue(facts.of(Unknown) or followed == [("./x", "test")], followed)


class EnvironmentTests(unittest.TestCase):
    @unittest.expectedFailure  # upstream #196: workflow- and job-level `env:` are not substituted into commands
    def test_workflow_and_job_env_are_substituted_into_command_lines(self) -> None:
        """`meson setup ${ARGS} build .` with `ARGS: -D werror=true` at the workflow or job level treats warnings as
        errors (dbus-broker's CI_MESON_ARGS)."""
        step = {"run": "meson setup ${ARGS} build ."}
        env = {"ARGS": "-D werror=true"}
        for level, files in {
            "workflow": _workflow({"steps": [step]}, env=env),
            "job": _workflow({"env": env, "steps": [step]}),
        }.items():
            with self.subTest(level=level):
                result = run_in_layout(
                    self, "Meson C++", warnings_as_errors, {"meson.build": "project('app', 'cpp')\n", **files}
                )
                self.assertEqual(result.status, Status.PASS, result)

    @unittest.expectedFailure  # upstream #284: a conditional `>> $GITHUB_ENV` export drops the steps it guards
    def test_a_conditional_github_env_export_keeps_the_guarded_steps(self) -> None:
        """`echo "SKIP=true" >> $GITHUB_ENV` inside a shell `if` sets SKIP only sometimes, so a later step with
        `if: env.SKIP != 'true'` may run and is read (zigtools/zls's ReleaseSafe release build)."""
        files = _workflow(
            {
                "steps": [
                    {"run": 'if [ -n "$X" ]; then\n  echo "SKIP=true" >> $GITHUB_ENV\nfi\n'},
                    {"uses": "mlugg/setup-zig@v2", "if": "env.SKIP != 'true'"},
                    {"run": "zig build -Doptimize=ReleaseSafe", "if": "env.SKIP != 'true'"},
                ]
            }
        )
        self.assertIn(("zig", "build", "-Doptimize=ReleaseSafe"), _argvs(_facts_of(files)))
        result = run_in_layout(self, "Zig build", hardening, files)
        self.assertEqual(result.status, Status.PASS, result)
